export function getAirstripNearbyAirports(prop, coordinates) {
  const list = [];
  if (prop?.nearest_airport?.code) {
    const dist = Number(prop.nearest_airport.distance_km) || 0;
    list.push({
      code: prop.nearest_airport.code,
      name: prop.nearest_airport.name,
      distance_km: dist,
      evtol_mins: Math.max(4, Math.ceil((dist / 240) * 60)),
      is_nearest: true,
    });
  }
  if (Array.isArray(coordinates) && coordinates.length === 2) {
    const [lon, lat] = coordinates;
    const computed = INDIAN_HUB_AIRPORTS
      .filter((ap) => ap.code !== prop?.nearest_airport?.code)
      .map((ap) => {
        const dist = haversineKm(lat, lon, ap.lat, ap.lon);
        return {
          code: ap.code,
          name: ap.name,
          distance_km: dist,
          bearing_deg: bearingDegrees(lat, lon, ap.lat, ap.lon),
          evtol_mins: Math.max(5, Math.ceil((dist / 240) * 60)),
          is_nearest: false,
        };
      })
      .sort((a, b) => a.distance_km - b.distance_km)
      .slice(0, 2);
    list.push(...computed);
  }
  return list;
}

