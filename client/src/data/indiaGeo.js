export const STATES_AND_UTS = INDIA_GEO_DATA;

export const ALL_STATES = INDIA_GEO_DATA.filter((s) => s.type === 'State');
export const ALL_UNION_TERRITORIES = INDIA_GEO_DATA.filter((s) => s.type === 'Union Territory');

export const ALL_CAPITALS = INDIA_GEO_DATA.map((s) => ({
  state: s.name,
  type: s.type,
  capital: s.capital,
  coordinates: s.capital_coords,
}));

export const ALL_CITIES = INDIA_GEO_DATA.flatMap((s) =>
  s.cities.map((c) => ({
    ...c,
    state: s.name,
    stateType: s.type,
  }))
);

export function getCitiesByState(stateName) {
  const match = INDIA_GEO_DATA.find((s) => s.name.toLowerCase() === stateName.toLowerCase());
  return match ? match.cities : [];
}

export function getStateByCity(cityName) {
  const city = ALL_CITIES.find((c) => c.name.toLowerCase() === cityName.toLowerCase());
  return city ? city.state : null;
}
